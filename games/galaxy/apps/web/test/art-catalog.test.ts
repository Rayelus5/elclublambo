import { ART, type ArtGroup, type ArtInfo } from '@galaxy/shared';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { expect, test } from 'vitest';
import { SPRITES } from '../src/arena/sprites';
import { BOSSES } from '../src/arena/sprites/bosses';
import { FAUNA2 } from '../src/arena/sprites/fauna2';
import { FORMS } from '../src/arena/sprites/forms';
import { ICONS } from '../src/arena/sprites/icons';
import { PROBE_ART } from '../src/arena/sprites/probe-art';

// The arena's drawings as a catalog the server and the CLI can read (the content editor, 2026-11-16, P5): packages/
// shared/src/config/art-catalog.ts is generated from SPRITES. A drawing added or changed fails here until it is
// regenerated: GALAXY_WRITE_ART=1 pnpm exec vitest run --project web apps/web/test/art-catalog.test.ts

const FAUNA = ['mite', 'cell', 'cellet', 'ray', 'spitter', 'shell', ...Object.keys(FAUNA2)];
const CORES = ['hive', ...Object.keys(BOSSES), ...Object.keys(FORMS)];

function catalog(): Record<string, ArtInfo> {
  const group = (id: string): ArtGroup =>
    id in PROBE_ART ? 'sondas' : id in ICONS ? 'iconos' : CORES.includes(id) ? 'nucleos' : FAUNA.includes(id) ? 'fauna' : 'otros';
  const out: Record<string, ArtInfo> = {};
  for (const id of Object.keys(SPRITES).sort()) {
    const def = SPRITES[id]!;
    out[id] = { group: group(id), w: def.w, h: def.h, frames: def.frames.length };
  }
  return out;
}

test('el catálogo de arte es el de la arena', () => {
  const now = catalog();
  if (process.env['GALAXY_WRITE_ART']) {
    const lines = Object.entries(now).map(([id, a]) => `  '${id}': { group: '${a.group}', w: ${a.w}, h: ${a.h}, frames: ${a.frames} },`);
    const file = [
      '// GENERATED by apps/web/test/art-catalog.test.ts from the arena\'s SPRITES: do not edit. After adding or changing a drawing,',
      '// run it with GALAXY_WRITE_ART=1 (see that test).',
      "import type { ArtInfo } from './art';",
      '',
      'export const ART: Record<string, ArtInfo> = {',
      ...lines,
      '};',
      '',
    ].join('\n');
    writeFileSync(resolve(__dirname, '../../../packages/shared/src/config/art-catalog.ts'), file);
  }
  expect(ART).toEqual(now);
});
