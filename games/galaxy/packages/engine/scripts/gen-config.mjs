// Writes src/config/generated.ts from config/*.yaml (ENGINE_PORT §4): `pnpm -C packages/engine gen:config`.
//
// The YAML is parsed into Maps, so key order never depends on JavaScript's object rules (integer-like keys such as
// arms "2".."6" would be reordered). Mappings whose order decides results (trait values, palettes) become arrays or a
// Map; the rest become plain objects, which keep insertion order for non-integer keys — a guard rejects the others.
// test/config.test.ts compares the result with PyYAML's own parse (golden/v1/config.json) and with this file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = new URL('../', import.meta.url);
const read = (name) => parse(readFileSync(new URL(`config/${name}.yaml`, root), 'utf8'), { mapAsMap: true });

function plain(value, path) {
  if (value instanceof Map) {
    const out = {};
    for (const [k, v] of value) {
      const key = String(k);
      if (/^\d+$/.test(key)) throw new Error(`${path}.${key}: integer-like key would lose its YAML order`);
      out[key] = plain(v, `${path}.${key}`);
    }
    return out;
  }
  if (Array.isArray(value)) return value.map((v, i) => plain(v, `${path}[${i}]`));
  return value;
}

function traitsConfig(doc) {
  const traits = {};
  for (const [key, spec] of doc.get('traits')) {
    const values = [];
    for (const [value, v] of spec.get('values')) {
      const requires = v.get('requires');
      values.push({
        value: String(value),
        name: v.get('name'),
        weight: v.get('weight'),
        ...(requires ? { requires: plain(requires, `traits.${key}.${value}.requires`) } : {}),
      });
    }
    const requires = spec.get('requires');
    traits[key] = {
      key,
      label: spec.get('label'),
      ...(requires ? { requires: plain(requires, `traits.${key}.requires`) } : {}),
      values,
    };
  }
  return { drawOrder: doc.get('draw_order'), traits, rules: plain(doc.get('rules'), 'rules') };
}

const json = (value) => JSON.stringify(value, null, 2);

export function generate() {
  const traits = read('traits');
  const palettes = read('palettes').get('palettes');
  const visuals = read('visuals');
  const collection = read('collection');
  const paletteEntries = [...palettes].map(([key, spec]) => [String(key), plain(spec, `palettes.${key}`)]);
  return `// Generated by scripts/gen-config.mjs from config/*.yaml. Do not edit: change the YAML and run
// \`pnpm -C packages/engine gen:config\` (test/config.test.ts fails while this file is stale).
import type { PaletteSpec, PostfxConfig, RenderConfig, TraitsConfig, VisualsConfig } from './types';

function freeze<T>(value: T): T {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const v of Object.values(value)) freeze(v);
    Object.freeze(value);
  }
  return value;
}

export const MASTER_SEED = ${collection.get('seeds').get('master')};

export const TRAITS = freeze<TraitsConfig>(${json(traitsConfig(traits))});

export const PALETTES: ReadonlyMap<string, PaletteSpec> = new Map(
  freeze<Array<[string, PaletteSpec]>>(${json(paletteEntries)}),
);

export const VISUALS = freeze<VisualsConfig>(${json(plain(visuals, 'visuals'))});

export const RENDER = freeze<RenderConfig>(${json(plain(collection.get('render'), 'render'))});

export const POSTFX = freeze<PostfxConfig>(${json(plain(collection.get('postfx'), 'postfx'))});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('src/config/generated.ts', root), generate());
  console.log('wrote src/config/generated.ts');
}
