import type { Content, WeaponLevel } from './types';

// The default run content of M3a (plan «Valores de partida»): the Outer Nebula sector, its fauna and boss, the Lumen
// probe, 7 weapons, 8 passives, the 11 elements and the relic tuning. Every number is a starting value, calibrated by
// the bot simulation (packages/sim/test/calibration.test.ts) and editable in the live config.

type Row = { [K in keyof WeaponLevel]?: number | number[] };

/** Five weapon levels from per-field values: a number repeats, a list gives one value per level. */
function levels(row: Row, n = 5): WeaponLevel[] {
  const at = (k: keyof WeaponLevel, i: number): number => {
    const v = row[k];
    if (v === undefined) return 0;
    return typeof v === 'number' ? v : v[i]!;
  };
  return Array.from({ length: n }, (_, i) => ({
    damage: at('damage', i),
    cooldown: at('cooldown', i),
    count: at('count', i),
    pierce: at('pierce', i),
    speed: at('speed', i),
    area: at('area', i),
    duration: at('duration', i),
    range: at('range', i),
    bounces: at('bounces', i),
    knockback: at('knockback', i),
    interval: at('interval', i),
  }));
}

